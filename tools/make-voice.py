"""Pre-records every phrase the game speaks with a natural British Piper voice.

Usage:
  python tools/make-voice.py phrases.json path/to/en_GB-voice.onnx [out_dir]

Writes out_dir/<id>.mp3 for each phrase and out_dir/manifest.js, which maps
phrase text -> clip id. Clips that already exist are reused, so it is quick to
re-run after adding phrases. Delete out_dir to re-record everything (e.g. with
a different voice).
"""
import hashlib, io, json, os, subprocess, sys, wave
from piper import PiperVoice, SynthesisConfig

phrases_path, model = sys.argv[1], sys.argv[2]
out = sys.argv[3] if len(sys.argv) > 3 else 'audio'
os.makedirs(out, exist_ok=True)
phrases = json.load(open(phrases_path, encoding='utf-8'))
voice = PiperVoice.load(model, config_path=model + '.json')
# a touch slower than normal speech, with a bit more expression, for 5-6 year olds
cfg = SynthesisConfig(length_scale=1.1, noise_scale=0.75, noise_w_scale=0.9)

manifest, made = {}, 0
for i, text in enumerate(phrases):
    cid = hashlib.sha1(text.encode('utf-8')).hexdigest()[:12]
    manifest[text] = cid
    mp3 = os.path.join(out, cid + '.mp3')
    if os.path.exists(mp3):
        continue
    buf = io.BytesIO()
    with wave.open(buf, 'wb') as wf:
        voice.synthesize_wav(text, wf, syn_config=cfg)
    # mono MP3: trim long silences at the ends, small files that play on every phone
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-f', 'wav', '-i', 'pipe:0',
                    '-af', 'silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.05,areverse,silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.1,areverse',
                    '-ac', '1', '-ar', '22050', '-c:a', 'libmp3lame', '-b:a', '48k', mp3],
                   input=buf.getvalue(), check=True)
    made += 1
    if made % 200 == 0:
        print(f'{made} new clips ({i + 1}/{len(phrases)})', flush=True)

# drop clips that are no longer used
keep = {c + '.mp3' for c in manifest.values()}
for f in os.listdir(out):
    if f.endswith('.mp3') and f not in keep:
        os.remove(os.path.join(out, f))
with open(os.path.join(out, 'manifest.js'), 'w', encoding='utf-8') as f:
    f.write('/* generated by tools/make-voice.py: phrase -> clip id (audio/<id>.mp3) */\n')
    f.write('window.Y1A_AUDIO=' + json.dumps(manifest, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n')
print(f'done: {len(manifest)} phrases, {made} newly recorded')
